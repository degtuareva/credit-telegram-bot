package com.example.creditbot.domain;

/**
 * Перечисление типов платежей по кредиту.
 * <p>
 * Определяет доступные схемы расчёта: аннуитетную и дифференцированную.
 * </p>
 *
 * @author degtuareva
 * @version 1.0
 */

public enum PaymentType {
    /**
     * Аннуитетный платёж (равные платежи каждый месяц)
     */
    ANNUITY,
    /**
     * Дифференцированный платёж (уменьшающиеся платежи)
     */
    DIFFERENTIAL

}
